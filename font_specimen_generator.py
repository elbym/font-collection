def main():
    parser = argparse.ArgumentParser(
        description="Generiert Font-Specimen-Vorschaubilder für alle Schriftfamilien in einem Ordner.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Beispiele:
  python font_specimen_generator.py --input ./fonts --output ./previews
  python font_specimen_generator.py --input ./fonts --output ./previews --theme white
  python font_specimen_generator.py --input ./fonts --output ./previews --width 1400 --theme cream
  python font_specimen_generator.py --input ./fonts --output ./previews --overwrite
  python font_specimen_generator.py --input ./fonts --output ./previews --wordlist ./meine_woerter.txt
        """
    )
    parser.add_argument("--input",    "-i", required=True,
                        help="Ordner mit Schriftdateien (wird rekursiv durchsucht)")
    parser.add_argument("--output",   "-o", required=True,
                        help="Ausgabeordner für die PNG-Vorschauen")
    parser.add_argument("--width",    "-w", type=int, default=1000,
                        help="Breite der Vorschaubilder in Pixel (Standard: 1000)")
    parser.add_argument("--theme",    "-t", default="dark",
                        choices=list(THEMES.keys()) + ["random", "random-dark", "random-light"],
                        help="Farbschema: dark | white | cream | random | random-dark | random-light (Standard: dark)")
    parser.add_argument("--wordlist", default=None,
                        help="Pfad zur Wortliste (Standard: wordlist.txt neben dem Script)")
    parser.add_argument("--overwrite", action="store_true",
                        help="Bereits vorhandene Vorschauen überschreiben")

    args = parser.parse_args()

    if args.width < 400:
        print("Fehler: Mindestbreite ist 400px.")
        sys.exit(1)

    process_folder(
        input_folder  = args.input,
        output_folder = args.output,
        width         = args.width,
        theme         = args.theme,
        overwrite     = args.overwrite,
        wordlist_path = args.wordlist,
    )


if __name__ == "__main__":
    main()
